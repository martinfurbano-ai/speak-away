import Foundation

/// The rules for borrowing the clipboard to paste a dictation and giving it back.
///
/// Every dictation goes on the clipboard marked as ours (and as transient, so clipboard managers skip it).
/// When the clipboard is given back it is always the user's own content: if what is on the clipboard is an
/// earlier dictation of ours, the last real user clipboard is used instead. That way a Cmd+V that an app
/// handles late can never paste the previous transcription again.
public enum ClipboardKeeper {
    /// Pasteboard type that marks a dictation put there by Speak Away.
    public static let markerType = "com.opensourceeverything.speakaway.dictation"

    /// Written next to the text. The `org.nspasteboard` types are the convention clipboard managers
    /// (Maccy, Raycast, Paste, Alfred) follow to ignore short-lived content.
    public static let markerTypes = [markerType, "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    /// How long the dictation stays on the clipboard before the user's content comes back.
    /// Busy apps (Electron, browsers, big terminals) can handle Cmd+V well after it was sent.
    public static let restoreDelay: TimeInterval = 1.5

    /// True when a clipboard item with these types is a dictation of ours.
    public static func isOurs(types: [String]) -> Bool {
        types.contains(markerType)
    }

    /// The clipboard to give back after pasting: the current one when it belongs to the user, else the
    /// last one that did. Nil means there is nothing of the user's to give back.
    public static func userClipboard<Snapshot>(current: Snapshot, currentIsOurs: Bool, remembered: Snapshot?) -> Snapshot? {
        currentIsOurs ? remembered : current
    }

    /// Give the clipboard back only if nobody copied anything after the dictation went on it.
    public static func mayRestore(changeCountNow: Int, ours: Int) -> Bool {
        changeCountNow == ours
    }
}
